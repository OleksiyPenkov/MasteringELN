import katex from 'katex';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { KATEX_MACROS } from '../src/lib/katex-macros.mjs';

const FORMULAS = {
  bragg: String.raw`K = \frac{A}{2 \cdot F_n \cdot N}`,
  parratt: String.raw`\text{Proc} \rightarrow \text{Specimen} \rightarrow \text{Action} \rightarrow \text{File} \rightarrow \text{Value}`,
};

const html = Object.entries(FORMULAS)
  .map(([name, tex]) => `<div class="ghost ghost-${name}">${katex.renderToString(tex, {
    displayMode: true, macros: { ...KATEX_MACROS }, throwOnError: true, strict: true, output: 'html',
  })}</div>`)
  .join('\n');

const out = fileURLToPath(new URL('./cover-math.html', import.meta.url));
writeFileSync(out, `<!-- Generated by pdf-build/cover-math.mjs. Edit the script, not this file. -->\n${html}\n`);
console.log(`wrote ${out}`);
